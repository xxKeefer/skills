#!/usr/bin/env python3
"""Run: python3 no_ai_attribution_test.py  (exits non-zero on failure)."""
import json
import pathlib
import subprocess
import sys
import tempfile

import no_ai_attribution

CWD = pathlib.Path(tempfile.mkdtemp())
(CWD / "msg-bad.txt").write_text("feat: x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\n")
(CWD / "msg-ok.txt").write_text("feat: x\n\nCo-Authored-By: Sam <sam@example.com>\n")

HEREDOC_BAD = """git commit -F - <<'EOF'
feat: add it

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
EOF"""
HEREDOC_OK = """git commit -F - <<'EOF'
feat: it's done

Body text.
EOF"""

CASES = [
    # (command, should_block)
    ('git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"', True),
    ('git commit -m "fix: y\n\nCo-authored-by: GitHub Copilot <copilot@github.com>"', True),
    ('git commit -m "docs: z\n\nGenerated with [Claude Code](https://claude.com/claude-code)"', True),
    ('git commit -m "chore: w\n\n🤖 Generated by ChatGPT"', True),
    (HEREDOC_BAD, True),
    ("git commit -F msg-bad.txt", True),
    ("git commit --file=msg-bad.txt", True),
    ('git -C repo commit -m "x\n\nCo-Authored-By: Gemini"', True),
    ('cd repo && git commit -am "x\n\nCo-Authored-By: Cursor Agent"', True),
    # clean commits
    ('git commit -m "feat: add login"', False),
    ('git commit -m "x" -m "Co-Authored-By: Sam <sam@example.com>"', False),
    ("git commit -F msg-ok.txt", False),
    (HEREDOC_OK, False),
    ("git commit --amend --no-edit", False),
    # not a commit
    ('git log --grep "Co-Authored-By: Claude"', False),
    ('echo "Co-Authored-By: Claude" > notes.txt', False),
    # unreadable file and stray quote fail open
    ("git commit -F missing.txt", False),
    ('git commit -m "unterminated', False),
]


def main():
    failures = []
    for cmd, should_block in CASES:
        blocked = no_ai_attribution.evaluate(cmd, CWD) is not None
        if blocked != should_block:
            failures.append(f"  {cmd!r}: expected block={should_block}, got {blocked}")

    script = pathlib.Path(__file__).parent / "no_ai_attribution.py"
    for stdin, should_print in [
        (json.dumps({"tool_input": {"command": HEREDOC_BAD}, "cwd": str(CWD)}), True),
        (json.dumps({"tool_input": {"command": "ls"}}), False),
        ("not json", False),
    ]:
        out = subprocess.run([sys.executable, str(script)], input=stdin, capture_output=True, text=True).stdout
        if bool(out.strip()) != should_print:
            failures.append(f"  stdin {stdin[:30]!r}: expected output={should_print}, got {out!r}")

    if failures:
        print(f"FAIL ({len(failures)}):")
        print("\n".join(failures))
        sys.exit(1)
    print(f"OK ({len(CASES) + 3} cases)")


if __name__ == "__main__":
    main()
